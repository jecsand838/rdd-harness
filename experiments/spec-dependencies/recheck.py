"""Read-only qualification of frozen inputs; all build/run output goes to scratch.

Requires exact cargo-tauri2.12.1 and wasm-bindgen0.2.129 installed via the
documented locked commands. RDD_QUAL_TOOL_BIN may point to their bin directory.
"""
import hashlib, json, os, pathlib, shutil, subprocess, tempfile, tomllib

SOURCE = pathlib.Path(__file__).resolve().parent
INPUTS = ["Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "capture.py", "recheck.py"]
for directory in ["native", "ui", "desktop"]:
    INPUTS += [str(p.relative_to(SOURCE)) for p in (SOURCE/directory).rglob("*")
               if p.is_file() and (p.suffix in {".rs", ".toml", ".html", ".js", ".png"}
                  or str(p.relative_to(SOURCE)).startswith("desktop/capabilities/")
                  or p.name=="tauri.conf.json") and not {"gen", "autogenerated"}.intersection(p.relative_to(SOURCE).parts)]
INPUTS = sorted(set(INPUTS))

def hashes():
    return {name:hashlib.sha256((SOURCE/name).read_bytes()).hexdigest() for name in INPUTS}

def tool(name, expected):
    candidates=[]
    if os.environ.get("RDD_QUAL_TOOL_BIN"): candidates.append(pathlib.Path(os.environ["RDD_QUAL_TOOL_BIN"])/name)
    candidates.append(SOURCE/"tools/bin"/name)
    found=shutil.which(name)
    if found: candidates.append(pathlib.Path(found))
    for candidate in candidates:
        if candidate.is_file():
            result=subprocess.run([str(candidate),"--version"],text=True,capture_output=True,check=True)
            parts=result.stdout.strip().split()
            if len(parts)!=2 or parts[1]!=expected: raise SystemExit(f"wrong {name} version: {result.stdout.strip()}")
            return candidate.resolve()
    raise SystemExit(f"missing {name}{expected}; install the documented exact version")

before=hashes()
scratch=pathlib.Path(tempfile.mkdtemp(prefix="rdd-dependency-recheck-",dir="/private/tmp"))
for name in INPUTS:
    destination=scratch/name; destination.parent.mkdir(parents=True,exist_ok=True)
    shutil.copyfile(SOURCE/name,destination)

# Rebase only a path dependency in the disposable copy. The external canonical
# generated crate is read from the same resolved path as the original manifest.
contracts=None
for directory in ["ui","desktop"]:
    original=SOURCE/directory/"Cargo.toml"
    dependency=tomllib.loads(original.read_text())["dependencies"]["rdd-contracts"]["path"]
    resolved=(original.parent/dependency).resolve()
    if not (resolved/"Cargo.toml").is_file(): raise SystemExit(f"missing generated contract input: {resolved}")
    contracts=resolved
    copied=scratch/directory/"Cargo.toml"
    copied.write_text(copied.read_text().replace('path = "'+dependency+'"','path = "'+str(resolved)+'"'))

contracts_before={str(p.relative_to(contracts)):hashlib.sha256(p.read_bytes()).hexdigest()
                  for p in contracts.rglob("*") if p.is_file() and p.suffix in {".rs", ".toml"}}
bin_dir=scratch/"tools/bin"; bin_dir.mkdir(parents=True)
for name,version in [("cargo-tauri","2.12.1"),("wasm-bindgen","0.2.129")]:
    (bin_dir/name).symlink_to(tool(name,version))
environment=os.environ.copy(); environment["RDD_PROBE_HOLD_SECONDS"]="0"
target=pathlib.Path(os.environ.get("RDD_QUAL_TARGET_DIR", os.environ.get("CARGO_TARGET_DIR", "/private/tmp/rdd-dependency-qualification-target"))).resolve()
environment["CARGO_TARGET_DIR"]=str(target)
print(json.dumps({"scratch":str(scratch),"input_sha256":before,"generated_sha256":contracts_before}),flush=True)
for stage in ["native","ui","package","sign","launch"]:
    result=subprocess.run(["python3",str(scratch/"capture.py"),stage],cwd=scratch,env=environment)
    if result.returncode: raise SystemExit(result.returncode)
assert hashes()==before,"frozen qualification inputs changed"
contracts_after={str(p.relative_to(contracts)):hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in contracts.rglob("*") if p.is_file() and p.suffix in {".rs", ".toml"}}
assert contracts_after==contracts_before,"generated contract inputs changed"
binary=target/"release/bundle/macos/RDD Dependency Probe.app/Contents/MacOS/dependency-desktop-probe"
print(json.dumps({"status":"passed","scratch_logs":str(scratch/"logs"),"packaged_binary_sha256":hashlib.sha256(binary.read_bytes()).hexdigest(),"immutable_inputs":True}),flush=True)
